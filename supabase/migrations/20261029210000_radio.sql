-- Cria (`p_id` nulo) ou altera um estilo. Devolve o id.
CREATE OR REPLACE FUNCTION public.fn_radio_estilo_salvar(p_id smallint, p_nome text, p_playlist text, p_ativo boolean)
RETURNS smallint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_id smallint;
BEGIN
  IF NOT (SELECT public.fn_user_is_super_admin()) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: só o super_admin cuida da rádio' USING ERRCODE = '42501';
  END IF;
  IF p_nome IS NULL OR char_length(btrim(p_nome)) NOT BETWEEN 1 AND 40 THEN
    RAISE EXCEPTION 'NOME_INVALIDO: o nome do estilo vai de 1 a 40 letras' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (SELECT 1 FROM public.radio_estilos e
              WHERE lower(btrim(e.nome)) = lower(btrim(p_nome)) AND e.id IS DISTINCT FROM p_id) THEN
    RAISE EXCEPTION 'NOME_REPETIDO: já existe um estilo com esse nome' USING ERRCODE = '23505';
  END IF;

  IF p_id IS NULL THEN
    INSERT INTO public.radio_estilos (nome, playlist, ativo)
    VALUES (btrim(p_nome), nullif(btrim(p_playlist), ''), coalesce(p_ativo, true))
    RETURNING id INTO v_id;
  ELSE
    UPDATE public.radio_estilos
       SET nome = btrim(p_nome), playlist = nullif(btrim(p_playlist), ''), ativo = coalesce(p_ativo, ativo)
     WHERE id = p_id
    RETURNING id INTO v_id;
    IF v_id IS NULL THEN
      RAISE EXCEPTION 'ESTILO_SUMIU: esse estilo não existe mais' USING ERRCODE = 'P0002';
    END IF;
  END IF;
  RETURN v_id;
END;
$function$;

