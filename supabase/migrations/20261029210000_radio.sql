-- A votação da rodada no ar ainda pode ser mexida? (até fechar, 5 s antes do fim)
CREATE OR REPLACE FUNCTION public.fn_radio_conferir_votacao(r public.radio, p_rodada bigint)
RETURNS void
LANGUAGE plpgsql
STABLE
SET search_path TO ''
AS $function$
BEGIN
  IF NOT r.no_ar OR r.atual IS NULL THEN
    RAISE EXCEPTION 'RADIO_DESLIGADA: ligue a rádio antes' USING ERRCODE = 'P0001';
  END IF;
  IF r.rodada IS DISTINCT FROM p_rodada THEN
    RAISE EXCEPTION 'RODADA_PASSOU: essa música já acabou' USING ERRCODE = 'P0001';
  END IF;
  IF now() > r.inicia_em + make_interval(secs => (r.atual->>'duracao_s')::int) - interval '5 seconds' THEN
    RAISE EXCEPTION 'VOTACAO_ENCERRADA: a votação já fechou' USING ERRCODE = 'P0001';
  END IF;
END;
$function$;

