-- Troca a candidata da posição `p_posicao` (1 a 3). Os votos nela caem.
CREATE OR REPLACE FUNCTION public.fn_radio_candidata_trocar(p_rodada bigint, p_posicao integer, p_video text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  r       public.radio%ROWTYPE;
  v_nova  jsonb;
  v_velha text;
BEGIN
  IF NOT (SELECT public.fn_user_is_super_admin()) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: só o super_admin mexe na votação' USING ERRCODE = '42501';
  END IF;
  SELECT * INTO r FROM public.radio WHERE id = 1 FOR UPDATE;
  PERFORM public.fn_radio_conferir_votacao(r, p_rodada);
  IF p_posicao IS NULL OR p_posicao < 1 OR p_posicao > jsonb_array_length(r.candidatas) THEN
    RAISE EXCEPTION 'POSICAO_INVALIDA: escolha uma das candidatas' USING ERRCODE = '22023';
  END IF;
  v_nova := public.fn_radio_musica_json(p_video);
  IF v_nova IS NULL THEN
    RAISE EXCEPTION 'MUSICA_SUMIU: essa música não está no catálogo' USING ERRCODE = 'P0002';
  END IF;
  IF p_video = r.atual->>'video'
     OR EXISTS (SELECT 1 FROM jsonb_array_elements(r.candidatas) x WHERE x->>'video' = p_video) THEN
    RAISE EXCEPTION 'MUSICA_REPETIDA: essa música já está no ar ou na votação' USING ERRCODE = '22023';
  END IF;

  v_velha := r.candidatas -> (p_posicao - 1) ->> 'video';
  UPDATE public.radio SET candidatas = jsonb_set(r.candidatas, ARRAY[(p_posicao - 1)::text], v_nova),
                          atualizado_em = now()
   WHERE id = 1;
  DELETE FROM public.radio_votos WHERE rodada = r.rodada AND video = v_velha;
  PERFORM realtime.send(public.fn_radio_estado(), 'mudou', 'radio:geral', true);
  RETURN public.fn_radio_ler();
END;
$function$;

