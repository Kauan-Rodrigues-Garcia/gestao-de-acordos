-- ============================================================================
-- Rádio do Som ambiente: a mesma música, no mesmo ponto, para quem entrar
-- 29/10/2026 · pedido do Cleber
-- ============================================================================
--
-- Ninguém transmite áudio. O banco guarda só a PROGRAMAÇÃO: a música no ar e
-- a hora em que ela começou. Cada navegador faz a conta (agora − início) e
-- abre o player do YouTube naquele ponto. Quem entra no meio cai junto.
--
-- A próxima música é votada:
--
--   1. Quando uma música entra, o banco já escolhe 3 candidatas, cada uma de
--      um estilo diferente (sorteados entre os estilos ativos).
--   2. A votação abre 60 s antes do fim e fecha 5 s antes. Voto escondido:
--      ninguém vê a contagem enquanto vale. 1 voto por pessoa, dá para trocar.
--   3. No fim, o SORTEIO: o peso de cada candidata é 1 + votos. Sem voto
--      nenhum, 1/3 para cada. Votar aumenta a chance, não garante.
--   4. A contagem e a chance de cada uma aparecem DEPOIS, em `anterior`.
--
-- Quem sorteia é o primeiro navegador que chega ao fim da música
-- (`fn_radio_avancar`): a linha `radio` é travada, e quem chega um instante
-- depois recebe o mesmo resultado — a rodada já virou. Ninguém ouvindo, nada
-- roda: não há cron. Quem entra numa rádio parada faz ela sortear na hora.
--
-- O aviso de «virou a música» é um Broadcast `mudou` no tópico `radio:geral`
-- com o estado inteiro: quem ouve não precisa reler. Uma mensagem por música.
--
-- Quem ouve: `fn_radio_pode_ouvir()`. Hoje só o super_admin (teste do
-- Cleber). Abrir para mais gente é trocar o corpo dela — tudo passa por ali,
-- inclusive a policy do tópico.
--
-- O controle é do super_admin:
--   fn_radio_ligar               liga (a rádio começa já, com uma sorteada) ou
--                                desliga (para para todo mundo). Desligada,
--                                nada vira e ninguém vota.
--   fn_radio_avancar('pular')    sorteia a próxima na hora, com os votos que
--                                já houver.
--   fn_radio_tocar               põe no ar uma música escolhida do catálogo.
--   fn_radio_candidata_trocar    troca uma das 3 da votação (os votos nela
--                                caem); fn_radio_candidatas_sortear troca as 3.
--   fn_radio_musicas             busca no catálogo, para escolher.
-- O catálogo (estilos e músicas) também: cada estilo é uma playlist do
-- YouTube, que o painel lê pela Data API e manda inteira para
-- `fn_radio_importar`.
--
-- Nenhuma linha de dado existente muda. Reexecutável.
-- ============================================================================

BEGIN;

