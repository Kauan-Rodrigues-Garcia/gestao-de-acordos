GRANT EXECUTE ON FUNCTION public.fn_radio_pode_ouvir() TO authenticated;

-- ── O catálogo ──────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.radio_estilos (
  id            SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome          TEXT NOT NULL CHECK (char_length(btrim(nome)) BETWEEN 1 AND 40),
  -- O id da playlist do YouTube de onde as músicas vieram (para reimportar).
  playlist      TEXT CHECK (playlist IS NULL OR playlist ~ '^[A-Za-z0-9_-]{10,64}$'),
  ativo         BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  importado_em  TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS radio_estilos_nome_uk ON public.radio_estilos (lower(btrim(nome)));

CREATE TABLE IF NOT EXISTS public.radio_musicas (
  estilo_id  SMALLINT NOT NULL REFERENCES public.radio_estilos(id) ON DELETE CASCADE,
  video      TEXT NOT NULL CHECK (video ~ '^[A-Za-z0-9_-]{11}$'),
  titulo     TEXT NOT NULL,
  canal      TEXT NOT NULL DEFAULT '',
  capa       TEXT,
  duracao_s  INTEGER NOT NULL CHECK (duracao_s BETWEEN 30 AND 900),
  -- Falsa: o YouTube recusou tocar (fora do ar, bloqueada fora do site).
  ativa      BOOLEAN NOT NULL DEFAULT TRUE,
  -- Quando tocou por último: a escolha das candidatas evita as das últimas 3 h.
  tocou_em   TIMESTAMPTZ,
  PRIMARY KEY (estilo_id, video)
);

CREATE INDEX IF NOT EXISTS radio_musicas_video_idx ON public.radio_musicas (video);

-- ── O que está no ar: uma linha só ──────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.radio (
  id             SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  -- Ligada pelo super_admin. Desligada: sem música, sem votação.
  no_ar          BOOLEAN NOT NULL DEFAULT FALSE,
  no_ar_desde    TIMESTAMPTZ,
  -- Sobe 1 a cada música. O voto e o «virar» dizem de qual rodada são.
  rodada         BIGINT NOT NULL DEFAULT 0,
  -- {video, titulo, canal, capa, duracao_s, estilo}: uma cópia, para a música
  -- no ar não sumir se alguém mexer no catálogo no meio dela.
  atual          JSONB,
  inicia_em      TIMESTAMPTZ,
  -- As 3 da votação desta rodada, no mesmo formato de `atual`.
  candidatas     JSONB NOT NULL DEFAULT '[]'::jsonb,
  -- O resultado da rodada que acabou: {rodada, motivo, sorteada, votos,
  -- candidatas: [... + votos]}. É aqui que a contagem aparece.
  anterior       JSONB,
  atualizado_em  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO public.radio (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- Só os votos da rodada no ar: o «virar» apaga os das anteriores.
CREATE TABLE IF NOT EXISTS public.radio_votos (
  rodada     BIGINT NOT NULL,
  perfil_id  UUID NOT NULL,
  video      TEXT NOT NULL,
  votou_em   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (rodada, perfil_id)
);

COMMENT ON TABLE public.radio IS
  'Uma linha = a rádio do Som ambiente (música no ar, início, candidatas). Escrita só por '
  'fn_radio_avancar. Ver 20261029210000.';
COMMENT ON TABLE public.radio_votos IS
  'Voto na próxima música da rádio (1 por pessoa por rodada). Escondido até o sorteio. Ver 20261029210000.';

