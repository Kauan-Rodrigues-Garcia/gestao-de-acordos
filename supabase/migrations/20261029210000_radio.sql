-- As músicas de um estilo, lidas da playlist pelo painel:
--   [{video, titulo, canal, capa, duracao_s}, ...]   (até 500)
-- `p_substituir`: o estilo fica IGUAL à lista (as que saíram da playlist saem
-- daqui). Sem ele, só acrescenta. O que vier torto é ignorado, não estoura.
CREATE OR REPLACE FUNCTION public.fn_radio_importar(p_estilo smallint, p_musicas jsonb, p_substituir boolean DEFAULT true)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_limpa     jsonb;
  v_entraram  int := 0;
  v_sairam    int := 0;
BEGIN
  IF NOT (SELECT public.fn_user_is_super_admin()) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: só o super_admin cuida da rádio' USING ERRCODE = '42501';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.radio_estilos WHERE id = p_estilo) THEN
    RAISE EXCEPTION 'ESTILO_SUMIU: esse estilo não existe mais' USING ERRCODE = 'P0002';
  END IF;
  IF p_musicas IS NULL OR jsonb_typeof(p_musicas) <> 'array' OR jsonb_array_length(p_musicas) > 500 THEN
    RAISE EXCEPTION 'LISTA_INVALIDA: mande de 0 a 500 músicas' USING ERRCODE = '22023';
  END IF;

  -- A lista já limpa: uma vez cada vídeo, só o que passa nas regras.
  SELECT coalesce(jsonb_agg(jsonb_build_object(
           'video', y.video, 'titulo', y.titulo, 'canal', y.canal, 'capa', y.capa, 'duracao_s', y.duracao_s)), '[]'::jsonb)
    INTO v_limpa
    FROM (
      SELECT DISTINCT ON (x.video)
             x.video,
             left(btrim(x.titulo), 120) AS titulo,
             left(coalesce(btrim(x.canal), ''), 80) AS canal,
             CASE WHEN x.capa LIKE 'https://i.ytimg.com/%' THEN left(x.capa, 300) END AS capa,
             x.duracao_s
        FROM jsonb_to_recordset(p_musicas) AS x(video text, titulo text, canal text, capa text, duracao_s int)
       WHERE x.video ~ '^[A-Za-z0-9_-]{11}$'
         AND coalesce(btrim(x.titulo), '') <> ''
         AND x.duracao_s BETWEEN 30 AND 900
    ) y;

  IF p_substituir THEN
    DELETE FROM public.radio_musicas m
     WHERE m.estilo_id = p_estilo
       AND NOT EXISTS (SELECT 1 FROM jsonb_array_elements(v_limpa) i WHERE i->>'video' = m.video);
    GET DIAGNOSTICS v_sairam = ROW_COUNT;
  END IF;

  INSERT INTO public.radio_musicas AS m (estilo_id, video, titulo, canal, capa, duracao_s, ativa)
  SELECT p_estilo, i.video, i.titulo, i.canal, i.capa, i.duracao_s, true
    FROM jsonb_to_recordset(v_limpa) AS i(video text, titulo text, canal text, capa text, duracao_s int)
  ON CONFLICT (estilo_id, video) DO UPDATE
    SET titulo = excluded.titulo, canal = excluded.canal, capa = excluded.capa,
        duracao_s = excluded.duracao_s, ativa = true;
  GET DIAGNOSTICS v_entraram = ROW_COUNT;

  UPDATE public.radio_estilos SET importado_em = now() WHERE id = p_estilo;

  RETURN jsonb_build_object('musicas', v_entraram, 'sairam', v_sairam);
END;
$function$;

REVOKE ALL ON FUNCTION public.fn_radio_importar(smallint, jsonb, boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_radio_importar(smallint, jsonb, boolean) TO authenticated;

