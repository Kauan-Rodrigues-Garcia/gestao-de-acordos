-- ── O estado que todo ouvinte vê (sem o voto de ninguém) ────────────────────
CREATE OR REPLACE FUNCTION public.fn_radio_estado()
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT jsonb_build_object(
    'no_ar',      r.no_ar,
    'no_ar_desde', r.no_ar_desde,
    'rodada',     r.rodada,
    'atual',      r.atual,
    'inicia_em',  r.inicia_em,
    'candidatas', r.candidatas,
    'anterior',   r.anterior)
  FROM public.radio r
  WHERE r.id = 1;
$function$;

REVOKE ALL ON FUNCTION public.fn_radio_estado() FROM PUBLIC, anon, authenticated;

-- ── Ler: o estado, o relógio do banco e o meu voto ──────────────────────────
-- O relógio vai junto: a posição na música é contada pela hora do banco, não
-- pela do computador de cada um.
CREATE OR REPLACE FUNCTION public.fn_radio_ler()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF NOT (SELECT public.fn_radio_pode_ouvir()) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: a rádio ainda não está liberada para você' USING ERRCODE = '42501';
  END IF;
  RETURN public.fn_radio_estado() || jsonb_build_object(
    'agora',      now(),
    'meu_voto',   (SELECT v.video FROM public.radio_votos v
                    JOIN public.radio r ON r.id = 1 AND v.rodada = r.rodada
                   WHERE v.perfil_id = auth.uid()),
    'controla',   (SELECT public.fn_user_is_super_admin()));
END;
$function$;

REVOKE ALL ON FUNCTION public.fn_radio_ler() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_radio_ler() TO authenticated;

-- ── Votar ───────────────────────────────────────────────────────────────────
-- Abre 60 s antes do fim (3 s de folga para relógio) e fecha 5 s antes. Em
-- música curta, abre no começo.
CREATE OR REPLACE FUNCTION public.fn_radio_votar(p_rodada bigint, p_video text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  r      public.radio%ROWTYPE;
  v_fim  timestamptz;
BEGIN
  IF NOT (SELECT public.fn_radio_pode_ouvir()) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: a rádio ainda não está liberada para você' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO r FROM public.radio WHERE id = 1;
  IF NOT r.no_ar OR r.atual IS NULL OR r.rodada IS DISTINCT FROM p_rodada THEN
    RAISE EXCEPTION 'RODADA_PASSOU: essa música já acabou' USING ERRCODE = 'P0001';
  END IF;

  v_fim := r.inicia_em + make_interval(secs => (r.atual->>'duracao_s')::int);
  IF now() > v_fim - interval '5 seconds' THEN
    RAISE EXCEPTION 'VOTACAO_ENCERRADA: a votação já fechou' USING ERRCODE = 'P0001';
  END IF;
  IF now() < greatest(r.inicia_em, v_fim - interval '60 seconds') - interval '3 seconds' THEN
    RAISE EXCEPTION 'VOTACAO_FECHADA: a votação ainda não abriu' USING ERRCODE = 'P0001';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM jsonb_array_elements(r.candidatas) c WHERE c->>'video' = p_video) THEN
    RAISE EXCEPTION 'CANDIDATA_INVALIDA: essa música não está na votação' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.radio_votos AS v (rodada, perfil_id, video, votou_em)
  VALUES (p_rodada, auth.uid(), p_video, now())
  ON CONFLICT (rodada, perfil_id) DO UPDATE SET video = excluded.video, votou_em = excluded.votou_em;

  RETURN jsonb_build_object('rodada', p_rodada, 'meu_voto', p_video);
END;
$function$;

REVOKE ALL ON FUNCTION public.fn_radio_votar(bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_radio_votar(bigint, text) TO authenticated;

-- ── As 3 candidatas ─────────────────────────────────────────────────────────
-- Uma de cada estilo, com os estilos em ordem sorteada. Dentro do estilo, as
-- que não tocaram nas últimas 3 h primeiro. Com menos de 3 estilos, completa
-- com qualquer música. `p_fora`: a que acabou de entrar no ar.
CREATE OR REPLACE FUNCTION public.fn_radio_candidatas(p_fora text)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_lista   jsonb := '[]'::jsonb;
  v_videos  text[] := array_remove(ARRAY[p_fora], NULL);
  e         record;
  m         record;
BEGIN
  FOR e IN SELECT re.id, re.nome FROM public.radio_estilos re WHERE re.ativo ORDER BY random() LOOP
    EXIT WHEN jsonb_array_length(v_lista) >= 3;
    SELECT rm.video, rm.titulo, rm.canal, rm.capa, rm.duracao_s INTO m
      FROM public.radio_musicas rm
     WHERE rm.estilo_id = e.id AND rm.ativa AND rm.video <> ALL (v_videos)
     ORDER BY coalesce(rm.tocou_em > now() - interval '3 hours', false), random()
     LIMIT 1;
    IF FOUND THEN
      v_lista := v_lista || jsonb_build_array(jsonb_build_object(
        'video', m.video, 'titulo', m.titulo, 'canal', m.canal, 'capa', m.capa,
        'duracao_s', m.duracao_s, 'estilo', e.nome));
      v_videos := v_videos || m.video;
    END IF;
  END LOOP;

  WHILE jsonb_array_length(v_lista) < 3 LOOP
    SELECT rm.video, rm.titulo, rm.canal, rm.capa, rm.duracao_s, re.nome AS estilo INTO m
      FROM public.radio_musicas rm
      JOIN public.radio_estilos re ON re.id = rm.estilo_id AND re.ativo
     WHERE rm.ativa AND rm.video <> ALL (v_videos)
     ORDER BY coalesce(rm.tocou_em > now() - interval '3 hours', false), random()
     LIMIT 1;
    EXIT WHEN NOT FOUND;
    v_lista := v_lista || jsonb_build_array(jsonb_build_object(
      'video', m.video, 'titulo', m.titulo, 'canal', m.canal, 'capa', m.capa,
      'duracao_s', m.duracao_s, 'estilo', m.estilo));
    v_videos := v_videos || m.video;
  END LOOP;

  RETURN v_lista;
END;
$function$;

REVOKE ALL ON FUNCTION public.fn_radio_candidatas(text) FROM PUBLIC, anon, authenticated;

-- ── Uma música do catálogo, no formato de `atual` ──────────────────────────
CREATE OR REPLACE FUNCTION public.fn_radio_musica_json(p_video text)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT jsonb_build_object('video', m.video, 'titulo', m.titulo, 'canal', m.canal, 'capa', m.capa,
                            'duracao_s', m.duracao_s, 'estilo', e.nome)
    FROM public.radio_musicas m
    JOIN public.radio_estilos e ON e.id = m.estilo_id
   WHERE m.video = p_video AND m.ativa
   ORDER BY e.ativo DESC, e.id
   LIMIT 1;
$function$;

REVOKE ALL ON FUNCTION public.fn_radio_musica_json(text) FROM PUBLIC, anon, authenticated;

-- ── Virar a música (o sorteio) ──────────────────────────────────────────────
-- Interna: quem chama já travou a linha e conferiu as regras. `p_video`
-- nulo: sorteia entre as candidatas (peso 1 + votos); sem candidatas, qualquer
-- uma. `p_video` dado: entra ela (o «Tocar agora» do super_admin). Em todos os
-- casos, o resultado da rodada que sai vai para `anterior` com a contagem.
CREATE OR REPLACE FUNCTION public.fn_radio_virar(p_motivo text, p_video text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  r          public.radio%ROWTYPE;
  v_cands    jsonb := '[]'::jsonb;
  v_total    numeric := 0;
  v_votos    int := 0;
  v_sorte    numeric;
  v_acum     numeric := 0;
  v_nova     jsonb;
  c          jsonb;
  m          record;
  v_anterior jsonb;
BEGIN
  SELECT * INTO r FROM public.radio WHERE id = 1 FOR UPDATE;

  -- As candidatas com a contagem; só as que ainda estão no catálogo concorrem.
  SELECT coalesce(jsonb_agg(x.c || jsonb_build_object('votos', coalesce(v.n, 0)) ORDER BY x.ord), '[]'::jsonb)
    INTO v_cands
    FROM jsonb_array_elements(r.candidatas) WITH ORDINALITY AS x(c, ord)
    LEFT JOIN (SELECT rv.video, count(*)::int AS n FROM public.radio_votos rv
                WHERE rv.rodada = r.rodada GROUP BY rv.video) v ON v.video = x.c->>'video'
   WHERE EXISTS (SELECT 1 FROM public.radio_musicas rm WHERE rm.video = x.c->>'video' AND rm.ativa);

  FOR c IN SELECT value FROM jsonb_array_elements(v_cands) LOOP
    v_total := v_total + 1 + (c->>'votos')::int;
    v_votos := v_votos + (c->>'votos')::int;
  END LOOP;

  IF p_video IS NOT NULL THEN
    v_nova := public.fn_radio_musica_json(p_video);
  ELSIF v_total > 0 THEN
    v_sorte := random() * v_total;
    FOR c IN SELECT value FROM jsonb_array_elements(v_cands) LOOP
      v_acum := v_acum + 1 + (c->>'votos')::int;
      IF v_sorte < v_acum THEN v_nova := c - 'votos'; EXIT; END IF;
    END LOOP;
    -- `random()` é < 1, mas não custa: arredondamento cai na última.
    IF v_nova IS NULL THEN v_nova := (v_cands -> -1) - 'votos'; END IF;
  ELSE
    -- Sem candidatas (a primeira música, ou todas saíram): qualquer uma.
    SELECT rm.video, rm.titulo, rm.canal, rm.capa, rm.duracao_s, re.nome AS estilo INTO m
      FROM public.radio_musicas rm
      JOIN public.radio_estilos re ON re.id = rm.estilo_id AND re.ativo
     WHERE rm.ativa AND rm.video IS DISTINCT FROM (r.atual->>'video')
     ORDER BY coalesce(rm.tocou_em > now() - interval '3 hours', false), random()
     LIMIT 1;
    IF FOUND THEN
      v_nova := jsonb_build_object('video', m.video, 'titulo', m.titulo, 'canal', m.canal, 'capa', m.capa,
                                   'duracao_s', m.duracao_s, 'estilo', m.estilo);
    END IF;
  END IF;

  IF jsonb_array_length(v_cands) > 0 THEN
    v_anterior := jsonb_build_object(
      'rodada', r.rodada, 'motivo', p_motivo, 'sorteada', v_nova->>'video',
      'votos', v_votos, 'candidatas', v_cands);
  END IF;

  UPDATE public.radio SET
    rodada        = r.rodada + 1,
    atual         = v_nova,
    inicia_em     = CASE WHEN v_nova IS NULL THEN NULL ELSE now() END,
    candidatas    = CASE WHEN v_nova IS NULL THEN '[]'::jsonb ELSE public.fn_radio_candidatas(v_nova->>'video') END,
    anterior      = v_anterior,
    atualizado_em = now()
  WHERE id = 1;

  IF v_nova IS NOT NULL THEN
    UPDATE public.radio_musicas SET tocou_em = now() WHERE video = v_nova->>'video';
  END IF;
  DELETE FROM public.radio_votos WHERE rodada <= r.rodada;

  PERFORM realtime.send(public.fn_radio_estado(), 'mudou', 'radio:geral', true);
END;
$function$;

REVOKE ALL ON FUNCTION public.fn_radio_virar(text, text) FROM PUBLIC, anon, authenticated;

-- ── Avançar: o fim da música, o pular e o erro ─────────────────────────────
-- `p_motivo`:
--   'fim'   a música acabou. Antes do fim (3 s de folga), não faz nada.
--   'pular' o super_admin pulou. Sorteia já, com os votos que houver.
--   'erro'  o YouTube não tocou esta música (fora do ar, bloqueada fora do
--           site). Só vale nos primeiros 45 s: a música sai do catálogo
--           (`ativa = false`) e entra outra.
-- Rodada que já virou, ou rádio desligada: devolve o estado como está.
CREATE OR REPLACE FUNCTION public.fn_radio_avancar(p_rodada bigint, p_motivo text DEFAULT 'fim')
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  r      public.radio%ROWTYPE;
  v_fim  timestamptz;
BEGIN
  IF NOT (SELECT public.fn_radio_pode_ouvir()) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: a rádio ainda não está liberada para você' USING ERRCODE = '42501';
  END IF;
  IF p_motivo IS NULL OR p_motivo NOT IN ('fim', 'pular', 'erro') THEN
    RAISE EXCEPTION 'MOTIVO_INVALIDO: use fim, pular ou erro' USING ERRCODE = '22023';
  END IF;
  IF p_motivo = 'pular' AND NOT (SELECT public.fn_user_is_super_admin()) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: só o super_admin pula música' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO r FROM public.radio WHERE id = 1 FOR UPDATE;
  IF NOT r.no_ar OR r.rodada IS DISTINCT FROM p_rodada THEN
    RETURN public.fn_radio_ler();
  END IF;

  IF r.atual IS NOT NULL THEN
    v_fim := r.inicia_em + make_interval(secs => (r.atual->>'duracao_s')::int);
    IF p_motivo = 'fim' AND now() < v_fim - interval '3 seconds' THEN
      RETURN public.fn_radio_ler();
    END IF;
    IF p_motivo = 'erro' THEN
      IF now() > r.inicia_em + interval '45 seconds' THEN
        RETURN public.fn_radio_ler();
      END IF;
      UPDATE public.radio_musicas SET ativa = false WHERE video = r.atual->>'video';
    END IF;
  END IF;

  PERFORM public.fn_radio_virar(p_motivo, NULL);
  RETURN public.fn_radio_ler();
END;
$function$;

REVOKE ALL ON FUNCTION public.fn_radio_avancar(bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_radio_avancar(bigint, text) TO authenticated;

-- ── O controle (só o super_admin) ───────────────────────────────────────────

-- Liga (começa já, com uma sorteada) ou desliga (para para todo mundo).
CREATE OR REPLACE FUNCTION public.fn_radio_ligar(p_ligar boolean)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  r public.radio%ROWTYPE;
BEGIN
  IF NOT (SELECT public.fn_user_is_super_admin()) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: só o super_admin liga e desliga a rádio' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO r FROM public.radio WHERE id = 1 FOR UPDATE;
  IF coalesce(p_ligar, false) = r.no_ar THEN
    RETURN public.fn_radio_ler();
  END IF;

  IF p_ligar THEN
    -- Começa limpa: a votação de antes de desligar não vale.
    UPDATE public.radio SET no_ar = true, no_ar_desde = now(), atual = NULL, inicia_em = NULL,
                            candidatas = '[]'::jsonb, anterior = NULL WHERE id = 1;
    PERFORM public.fn_radio_virar('ligar', NULL);
  ELSE
    UPDATE public.radio SET no_ar = false, no_ar_desde = NULL, rodada = r.rodada + 1, atual = NULL,
                            inicia_em = NULL, candidatas = '[]'::jsonb, anterior = NULL, atualizado_em = now()
     WHERE id = 1;
    -- `WHERE TRUE`: pela API, o safeupdate recusa DELETE sem WHERE.
    DELETE FROM public.radio_votos WHERE TRUE;
    PERFORM realtime.send(public.fn_radio_estado(), 'mudou', 'radio:geral', true);
  END IF;
  RETURN public.fn_radio_ler();
END;
$function$;

REVOKE ALL ON FUNCTION public.fn_radio_ligar(boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_radio_ligar(boolean) TO authenticated;

-- Põe no ar uma música escolhida do catálogo, agora.
CREATE OR REPLACE FUNCTION public.fn_radio_tocar(p_video text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  r public.radio%ROWTYPE;
BEGIN
  IF NOT (SELECT public.fn_user_is_super_admin()) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: só o super_admin escolhe a música' USING ERRCODE = '42501';
  END IF;
  SELECT * INTO r FROM public.radio WHERE id = 1 FOR UPDATE;
  IF NOT r.no_ar THEN
    RAISE EXCEPTION 'RADIO_DESLIGADA: ligue a rádio antes' USING ERRCODE = 'P0001';
  END IF;
  IF public.fn_radio_musica_json(p_video) IS NULL THEN
    RAISE EXCEPTION 'MUSICA_SUMIU: essa música não está no catálogo' USING ERRCODE = 'P0002';
  END IF;
  PERFORM public.fn_radio_virar('trocar', p_video);
  RETURN public.fn_radio_ler();
END;
$function$;

