-- Busca no catálogo (título, canal ou estilo), para escolher. Até 40.
CREATE OR REPLACE FUNCTION public.fn_radio_musicas(p_busca text DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_termo text := '%' || lower(btrim(coalesce(p_busca, ''))) || '%';
BEGIN
  IF NOT (SELECT public.fn_user_is_super_admin()) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: só o super_admin cuida da rádio' USING ERRCODE = '42501';
  END IF;
  RETURN coalesce((
    SELECT jsonb_agg(jsonb_build_object(
             'video', x.video, 'titulo', x.titulo, 'canal', x.canal, 'capa', x.capa,
             'duracao_s', x.duracao_s, 'estilo', x.estilo, 'tocou_em', x.tocou_em) ORDER BY x.titulo)
      FROM (
        SELECT d.* FROM (
          SELECT DISTINCT ON (m.video) m.video, m.titulo, m.canal, m.capa, m.duracao_s, e.nome AS estilo, m.tocou_em
            FROM public.radio_musicas m
            JOIN public.radio_estilos e ON e.id = m.estilo_id
           WHERE m.ativa
             AND (lower(m.titulo) LIKE v_termo OR lower(m.canal) LIKE v_termo OR lower(e.nome) LIKE v_termo)
           ORDER BY m.video, e.ativo DESC, e.id
        ) d
        ORDER BY d.titulo
        LIMIT 40
      ) x), '[]'::jsonb);
END;
$function$;

REVOKE ALL ON FUNCTION public.fn_radio_musicas(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_radio_musicas(text) TO authenticated;

