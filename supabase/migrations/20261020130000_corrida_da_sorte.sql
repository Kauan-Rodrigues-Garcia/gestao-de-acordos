-- ============================================================================
-- Corrida da Sorte: o sorteio em forma de corrida, comandado pelo super_admin
-- ============================================================================
--
-- ## O pedido (20/10/2026, Cleber)
--
-- A gincana da vez sai da Caça aos Zumbis e vira uma corrida de bichinhos:
--
--   1. O super_admin, em Configurações → Geral, cria a corrida: o prêmio, quem
--      CORRE (cada um escolhe um bichinho entre três) e quem ASSISTE.
--   2. Quem corre recebe na hora o convite para escolher o bichinho. Só quem
--      corre; ninguém mais vê nada nessa fase.
--   3. Ele ABRE a corrida: o card «Assistir» aparece para quem foi chamado
--      (quem assiste e quem corre). Quem entra senta na arquibancada do lobby.
--   4. Ele GRAVA: o navegador dele sorteia o mapa, simula a corrida inteira e
--      grava o replay e a festa do fim em vídeo. Os arquivos sobem para o
--      bucket `corridas`, e o resumo fica em `corridas.gravacao`.
--   5. Ele INICIA: `inicia_em` é a hora do banco + 4 s. Cada tela toca a
--      mesma gravação a partir dessa hora (o relógio de cada um é acertado
--      pelo `agora` que vem em toda resposta), então todo mundo vê o mesmo
--      momento ao mesmo tempo, e quem chega atrasado entra no ponto certo.
--
-- Além da corrida, o card de DIVULGAÇÃO: um aviso que aparece só para quem o
-- super_admin escolher, avisando que vem aí uma corrida com prêmio.
--
-- ## O que mora aqui
--
--   corridas                        uma por corrida, com o estado e a gravação
--   corrida_pessoas                 quem corre e quem assiste (com nome, setor
--                                   e foto copiados na hora), a escolha do
--                                   bichinho (0, 1 ou 2) e quando entrou no lobby
--   corrida_divulgacoes, corrida_divulgacao_alvos   o card de divulgação
--
-- Ninguém lê nem escreve as tabelas direto: tudo passa pelas funções, que
-- conferem quem é a pessoa (as do super_admin, `fn_user_is_super_admin()`).
--
-- ## Os avisos (Broadcast do banco, como o resto do app desde 20261013170000)
--
--   corrida-eu:<usuario>     só da pessoa: entrou ou saiu de uma corrida, a
--                            corrida abriu, chegou um card de divulgação.
--                            O conteúdo é o próprio estado dela
--                            (`fn_corrida_minha`), então ninguém relê nada.
--   corrida-sala:<corrida>   de quem foi chamado para aquela corrida: o
--                            estado mudou, alguém entrou no lobby, alguém
--                            escolheu o bichinho.
--
-- Quem entra no lobby segue o freio da chefona: no máximo um aviso a cada
-- 1,5 s, com todos os que entraram desde o anterior. O app ainda confere a
-- lista a cada 30 s (`fn_corrida_lobby`), para o último que entrou não ficar
-- de fora quando ninguém mais entra depois dele.
--
-- ## O que NÃO mora aqui
--
-- A simulação e o desenho. A corrida é calculada uma vez, no navegador do
-- super_admin, e as outras telas só reproduzem os arquivos. Por isso o banco
-- não sabe quem vai ganhar até a gravação chegar.
--
-- Reexecutável.
-- ============================================================================

BEGIN;

SET LOCAL lock_timeout = '15s';

-- ── As tabelas ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.corridas (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome             TEXT        NOT NULL DEFAULT 'Corrida da Sorte' CHECK (length(nome) BETWEEN 1 AND 60),
  premio           TEXT        CHECK (premio IS NULL OR length(premio) <= 60),
  estado           TEXT        NOT NULL DEFAULT 'preparando'
                               CHECK (estado IN ('preparando', 'aberta', 'correndo', 'encerrada', 'cancelada')),
  criada_por       UUID,
  criada_em        TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  aberta_em        TIMESTAMPTZ,
  gravada_em       TIMESTAMPTZ,
  inicia_em        TIMESTAMPTZ,
  encerrada_em     TIMESTAMPTZ,
  gravacao         JSONB,
  vencedor         UUID,
  vencedor_nome    TEXT,
  lobby_avisado_em TIMESTAMPTZ,
  versao           INTEGER     NOT NULL DEFAULT 1
);

COMMENT ON TABLE public.corridas IS
  'Corrida da Sorte: uma linha por corrida (estado, horários e o resumo da gravação). Escrita só pelas funções fn_corrida_*. Ver 20261020130000.';

-- Uma corrida em andamento por vez.
CREATE UNIQUE INDEX IF NOT EXISTS corridas_uma_em_andamento
  ON public.corridas ((TRUE)) WHERE estado IN ('preparando', 'aberta', 'correndo');

CREATE TABLE IF NOT EXISTS public.corrida_pessoas (
  corrida_id   BIGINT      NOT NULL REFERENCES public.corridas (id) ON DELETE CASCADE,
  usuario      UUID        NOT NULL,
  corre        BOOLEAN     NOT NULL DEFAULT FALSE,
  assiste      BOOLEAN     NOT NULL DEFAULT FALSE,
  nome         TEXT        NOT NULL,
  setor        TEXT,
  foto         TEXT,
  escolha      SMALLINT    CHECK (escolha BETWEEN 0 AND 2),
  escolhida_em TIMESTAMPTZ,
  entrou_em    TIMESTAMPTZ,
  PRIMARY KEY (corrida_id, usuario),
  CHECK (corre OR assiste)
);

COMMENT ON TABLE public.corrida_pessoas IS
  'Corrida da Sorte: quem corre e quem assiste cada corrida, com nome, setor e foto copiados na hora, o bichinho escolhido (0..2) e a entrada no lobby. Escrita só pelas funções. Ver 20261020130000.';

CREATE INDEX IF NOT EXISTS corrida_pessoas_usuario ON public.corrida_pessoas (usuario, corrida_id DESC);
CREATE INDEX IF NOT EXISTS corrida_pessoas_entrada ON public.corrida_pessoas (corrida_id, entrou_em) WHERE entrou_em IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.corrida_divulgacoes (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo     TEXT        NOT NULL CHECK (length(titulo) BETWEEN 1 AND 80),
  mensagem   TEXT        NOT NULL CHECK (length(mensagem) BETWEEN 1 AND 400),
  premio     TEXT        CHECK (premio IS NULL OR length(premio) <= 60),
  criada_por UUID,
  criada_em  TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  expira_em  TIMESTAMPTZ NOT NULL
);

COMMENT ON TABLE public.corrida_divulgacoes IS
  'Corrida da Sorte: o card de divulgação que o super_admin manda para quem escolher. Ver 20261020130000.';

CREATE TABLE IF NOT EXISTS public.corrida_divulgacao_alvos (
  divulgacao_id BIGINT      NOT NULL REFERENCES public.corrida_divulgacoes (id) ON DELETE CASCADE,
  usuario       UUID        NOT NULL,
  fechado_em    TIMESTAMPTZ,
  PRIMARY KEY (divulgacao_id, usuario)
);

CREATE INDEX IF NOT EXISTS corrida_divulgacao_alvos_usuario ON public.corrida_divulgacao_alvos (usuario, divulgacao_id DESC);

-- Sem policy: ninguém lê nem escreve direto (só pelas funções).
ALTER TABLE public.corridas                 ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.corrida_pessoas          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.corrida_divulgacoes      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.corrida_divulgacao_alvos ENABLE ROW LEVEL SECURITY;
GRANT ALL ON public.corridas, public.corrida_pessoas, public.corrida_divulgacoes, public.corrida_divulgacao_alvos TO service_role;

-- ── Os estados em JSON ─────────────────────────────────────────────────────
-- A gravação só vai junto depois de gravada; antes, ninguém sabe o mapa.
CREATE OR REPLACE FUNCTION public.fn_corrida_json(p_id bigint)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT jsonb_build_object(
    'id', c.id, 'nome', c.nome, 'premio', c.premio, 'estado', c.estado, 'versao', c.versao,
    'criada_em', c.criada_em, 'aberta_em', c.aberta_em, 'gravada_em', c.gravada_em,
    'inicia_em', c.inicia_em, 'encerrada_em', c.encerrada_em,
    'gravacao', c.gravacao, 'vencedor', c.vencedor, 'vencedor_nome', c.vencedor_nome,
    'corredores', (SELECT count(*) FROM public.corrida_pessoas p WHERE p.corrida_id = c.id AND p.corre),
    'chamados',   (SELECT count(*) FROM public.corrida_pessoas p WHERE p.corrida_id = c.id),
    'escolheram', (SELECT count(*) FROM public.corrida_pessoas p WHERE p.corrida_id = c.id AND p.corre AND p.escolha IS NOT NULL),
    'no_lobby',   (SELECT count(*) FROM public.corrida_pessoas p WHERE p.corrida_id = c.id AND p.entrou_em IS NOT NULL)
  )
  FROM public.corridas c
  WHERE c.id = p_id;
$function$;

CREATE OR REPLACE FUNCTION public.fn_corrida_pessoa_json(p public.corrida_pessoas)
RETURNS jsonb
LANGUAGE sql
IMMUTABLE
SET search_path TO ''
AS $function$
  SELECT jsonb_build_object(
    'usuario', p.usuario, 'nome', p.nome, 'setor', p.setor, 'foto', p.foto,
    'corre', p.corre, 'assiste', p.assiste, 'escolha', p.escolha, 'entrou_em', p.entrou_em
  );
$function$;

-- O que a pessoa vê agora: a corrida em que foi chamada (se houver), o papel
-- dela e o card de divulgação ainda não fechado.
--   - Na fase de escolha («preparando»), só quem CORRE fica sabendo.
--   - Encerrada há mais de 15 min, a corrida sai da tela de todo mundo.
CREATE OR REPLACE FUNCTION public.fn_corrida_minha_de(p_usuario uuid)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_c   public.corridas%ROWTYPE;
  v_p   public.corrida_pessoas%ROWTYPE;
  v_div jsonb;
BEGIN
  SELECT c.* INTO v_c
    FROM public.corridas c
    JOIN public.corrida_pessoas p ON p.corrida_id = c.id AND p.usuario = p_usuario
   WHERE (c.estado IN ('aberta', 'correndo') OR (c.estado = 'preparando' AND p.corre)
          OR (c.estado = 'encerrada' AND c.encerrada_em > clock_timestamp() - interval '15 minutes'))
   ORDER BY c.id DESC
   LIMIT 1;
  IF FOUND THEN
    SELECT * INTO v_p FROM public.corrida_pessoas WHERE corrida_id = v_c.id AND usuario = p_usuario;
  END IF;

  SELECT jsonb_build_object('id', d.id, 'titulo', d.titulo, 'mensagem', d.mensagem, 'premio', d.premio, 'criada_em', d.criada_em)
    INTO v_div
    FROM public.corrida_divulgacao_alvos a
    JOIN public.corrida_divulgacoes d ON d.id = a.divulgacao_id
   WHERE a.usuario = p_usuario AND a.fechado_em IS NULL AND d.expira_em > clock_timestamp()
   ORDER BY d.id DESC
   LIMIT 1;

  RETURN jsonb_build_object(
    'agora', clock_timestamp(),
    'corrida', CASE WHEN v_c.id IS NULL THEN NULL ELSE public.fn_corrida_json(v_c.id) END,
    'eu', CASE WHEN v_c.id IS NULL THEN NULL ELSE public.fn_corrida_pessoa_json(v_p) END,
    'divulgacao', v_div
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_corrida_minha()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'NAO_AUTENTICADO' USING ERRCODE = '42501';
  END IF;
  RETURN public.fn_corrida_minha_de(auth.uid());
END;
$function$;

-- A sala inteira: quem corre e quem assiste, com foto, bichinho e entrada.
-- Só para quem foi chamado e para o super_admin.
CREATE OR REPLACE FUNCTION public.fn_corrida_posso_ver(p_corrida bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT public.fn_user_is_super_admin()
      OR EXISTS (SELECT 1 FROM public.corrida_pessoas p WHERE p.corrida_id = p_corrida AND p.usuario = auth.uid());
$function$;

CREATE OR REPLACE FUNCTION public.fn_corrida_sala(p_corrida bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'NAO_AUTENTICADO' USING ERRCODE = '42501';
  END IF;
  IF NOT public.fn_corrida_posso_ver(p_corrida) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: você não foi chamado para esta corrida' USING ERRCODE = '42501';
  END IF;
  RETURN jsonb_build_object(
    'agora', clock_timestamp(),
    'corrida', public.fn_corrida_json(p_corrida),
    'pessoas', coalesce((SELECT jsonb_agg(public.fn_corrida_pessoa_json(p) ORDER BY p.corre DESC, p.nome)
                           FROM public.corrida_pessoas p WHERE p.corrida_id = p_corrida), '[]'::jsonb)
  );
END;
$function$;

-- Quem entrou no lobby depois de `p_desde` (a conferência de 30 s do app).
CREATE OR REPLACE FUNCTION public.fn_corrida_lobby(p_corrida bigint, p_desde timestamptz)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF NOT public.fn_corrida_posso_ver(p_corrida) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: você não foi chamado para esta corrida' USING ERRCODE = '42501';
  END IF;
  RETURN jsonb_build_object(
    'agora', clock_timestamp(),
    'entraram', coalesce((SELECT jsonb_agg(jsonb_build_object('usuario', p.usuario, 'entrou_em', p.entrou_em) ORDER BY p.entrou_em)
                            FROM public.corrida_pessoas p
                           WHERE p.corrida_id = p_corrida AND p.entrou_em IS NOT NULL
                             AND (p_desde IS NULL OR p.entrou_em > p_desde)), '[]'::jsonb)
  );
END;
$function$;

-- ── Os avisos ──────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.fn_corrida_avisar_pessoa(p_usuario uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  PERFORM realtime.send(public.fn_corrida_minha_de(p_usuario), 'corrida', 'corrida-eu:' || p_usuario::text, true);
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_corrida_avisar_sala(p_corrida bigint, p_evento text, p_extra jsonb DEFAULT '{}'::jsonb)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  PERFORM realtime.send(
    jsonb_build_object('agora', clock_timestamp(), 'corrida', public.fn_corrida_json(p_corrida)) || p_extra,
    p_evento, 'corrida-sala:' || p_corrida::text, true);
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_realtime_posso_ouvir_corrida(p_topico text)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_id bigint;
BEGIN
  BEGIN
    v_id := split_part(p_topico, ':', 2)::bigint;
  EXCEPTION WHEN invalid_text_representation THEN
    RETURN false;
  END;
  RETURN public.fn_corrida_posso_ver(v_id);
END;
$function$;

-- ── O painel do super_admin ────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.fn_corrida_exigir_admin()
RETURNS void
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF NOT public.fn_user_is_super_admin() THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: só o super_admin comanda a corrida' USING ERRCODE = '42501';
  END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_corrida_painel()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_id bigint;
BEGIN
  PERFORM public.fn_corrida_exigir_admin();
  -- A em andamento; senão, a última que terminou.
  SELECT id INTO v_id FROM public.corridas
   ORDER BY (estado IN ('preparando', 'aberta', 'correndo')) DESC, id DESC LIMIT 1;
  RETURN jsonb_build_object(
    'agora', clock_timestamp(),
    'corrida', CASE WHEN v_id IS NULL THEN NULL ELSE public.fn_corrida_json(v_id) END,
    'pessoas', coalesce((SELECT jsonb_agg(public.fn_corrida_pessoa_json(p) ORDER BY p.corre DESC, p.nome)
                           FROM public.corrida_pessoas p WHERE p.corrida_id = v_id), '[]'::jsonb),
    'historico', coalesce((SELECT jsonb_agg(h ORDER BY (h->>'id')::bigint DESC) FROM (
                             SELECT jsonb_build_object('id', c.id, 'nome', c.nome, 'premio', c.premio, 'estado', c.estado,
                                                       'criada_em', c.criada_em, 'vencedor_nome', c.vencedor_nome) h
                               FROM public.corridas c ORDER BY c.id DESC LIMIT 8) x), '[]'::jsonb),
    'divulgacoes', coalesce((SELECT jsonb_agg(x.j ORDER BY x.id DESC) FROM (
                               SELECT d.id, jsonb_build_object('id', d.id, 'titulo', d.titulo, 'criada_em', d.criada_em, 'expira_em', d.expira_em,
                                        'alvos', (SELECT count(*) FROM public.corrida_divulgacao_alvos a WHERE a.divulgacao_id = d.id),
                                        'fecharam', (SELECT count(*) FROM public.corrida_divulgacao_alvos a WHERE a.divulgacao_id = d.id AND a.fechado_em IS NOT NULL)) j
                                 FROM public.corrida_divulgacoes d ORDER BY d.id DESC LIMIT 5) x), '[]'::jsonb)
  );
END;
$function$;

-- Corrida que ficou «correndo» depois do fim (ninguém clicou em encerrar):
-- 15 min depois da largada, ela não segura mais a próxima.
CREATE OR REPLACE FUNCTION public.fn_corrida_vencidas()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  UPDATE public.corridas
     SET estado = 'encerrada', encerrada_em = clock_timestamp(), versao = versao + 1
   WHERE estado = 'correndo' AND inicia_em < clock_timestamp() - interval '15 minutes';
END;
$function$;

-- Põe nome, setor e foto de cada pessoa (do cadastro, na hora).
CREATE OR REPLACE FUNCTION public.fn_corrida_por_pessoas(p_corrida bigint, p_corredores uuid[], p_plateia uuid[])
RETURNS uuid[]
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_antes uuid[];
  v_depois uuid[];
BEGIN
  SELECT coalesce(array_agg(usuario), '{}') INTO v_antes FROM public.corrida_pessoas WHERE corrida_id = p_corrida;

  DELETE FROM public.corrida_pessoas
   WHERE corrida_id = p_corrida
     AND NOT (usuario = ANY (coalesce(p_corredores, '{}')) OR usuario = ANY (coalesce(p_plateia, '{}')));

  INSERT INTO public.corrida_pessoas AS cp (corrida_id, usuario, corre, assiste, nome, setor, foto)
  SELECT p_corrida, pf.id,
         pf.id = ANY (coalesce(p_corredores, '{}')),
         pf.id = ANY (coalesce(p_plateia, '{}')),
         coalesce(nullif(btrim(pf.nome), ''), 'Alguém'), nullif(btrim(s.nome), ''), nullif(btrim(pf.foto_url), '')
    FROM public.perfis pf
    LEFT JOIN public.setores s ON s.id = pf.setor_id
   WHERE pf.id = ANY (coalesce(p_corredores, '{}') || coalesce(p_plateia, '{}'))
  ON CONFLICT (corrida_id, usuario) DO UPDATE
     SET corre = EXCLUDED.corre, assiste = EXCLUDED.assiste,
         nome = EXCLUDED.nome, setor = EXCLUDED.setor, foto = EXCLUDED.foto,
         escolha = CASE WHEN EXCLUDED.corre THEN cp.escolha END;

  SELECT coalesce(array_agg(usuario), '{}') INTO v_depois FROM public.corrida_pessoas WHERE corrida_id = p_corrida;
  -- Quem precisa de aviso pessoal: quem entrou ou saiu da lista.
  RETURN ARRAY(SELECT u FROM unnest(v_antes || v_depois) u
                GROUP BY u HAVING count(*) = 1);
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_corrida_criar(p_nome text, p_premio text, p_corredores uuid[], p_plateia uuid[])
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_id bigint;
  v_u  uuid;
  v_n  int;
BEGIN
  PERFORM public.fn_corrida_exigir_admin();
  PERFORM public.fn_corrida_vencidas();
  IF EXISTS (SELECT 1 FROM public.corridas WHERE estado IN ('preparando', 'aberta', 'correndo')) THEN
    RAISE EXCEPTION 'JA_TEM_UMA: termine ou cancele a corrida em andamento antes de criar outra' USING ERRCODE = 'P0001';
  END IF;
  SELECT count(DISTINCT u) INTO v_n FROM unnest(coalesce(p_corredores, '{}')) u;
  IF v_n < 2 THEN
    RAISE EXCEPTION 'POUCA_GENTE: a corrida precisa de pelo menos 2 pessoas correndo' USING ERRCODE = 'P0001';
  END IF;
  IF v_n > 300 THEN
    RAISE EXCEPTION 'GENTE_DEMAIS: no máximo 300 pessoas correndo' USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO public.corridas (nome, premio, criada_por)
  VALUES (coalesce(nullif(btrim(p_nome), ''), 'Corrida da Sorte'), nullif(btrim(p_premio), ''), auth.uid())
  RETURNING id INTO v_id;

  PERFORM public.fn_corrida_por_pessoas(v_id, p_corredores, p_plateia);

  -- Só quem corre fica sabendo agora: é a vez de escolher o bichinho.
  FOR v_u IN SELECT usuario FROM public.corrida_pessoas WHERE corrida_id = v_id AND corre LOOP
    PERFORM public.fn_corrida_avisar_pessoa(v_u);
  END LOOP;
  RETURN public.fn_corrida_painel();
END;
$function$;

-- Trocar quem corre, quem assiste ou o prêmio: só antes de gravar.
CREATE OR REPLACE FUNCTION public.fn_corrida_ajustar(p_corrida bigint, p_premio text, p_corredores uuid[], p_plateia uuid[])
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_c public.corridas%ROWTYPE;
  v_u uuid;
  v_n int;
BEGIN
  PERFORM public.fn_corrida_exigir_admin();
  SELECT * INTO v_c FROM public.corridas WHERE id = p_corrida FOR UPDATE;
  IF NOT FOUND OR v_c.estado NOT IN ('preparando', 'aberta') THEN
    RAISE EXCEPTION 'NAO_DA: a corrida já largou ou terminou' USING ERRCODE = 'P0001';
  END IF;
  IF v_c.gravada_em IS NOT NULL THEN
    RAISE EXCEPTION 'JA_GRAVADA: a corrida já foi gravada com essas pessoas e esse prêmio; descarte a gravação para mudar' USING ERRCODE = 'P0001';
  END IF;
  SELECT count(DISTINCT u) INTO v_n FROM unnest(coalesce(p_corredores, '{}')) u;
  IF v_n < 2 OR v_n > 300 THEN
    RAISE EXCEPTION 'POUCA_GENTE: a corrida precisa de 2 a 300 pessoas correndo' USING ERRCODE = 'P0001';
  END IF;

  UPDATE public.corridas SET premio = nullif(btrim(p_premio), ''), versao = versao + 1 WHERE id = p_corrida;
  FOR v_u IN SELECT unnest(public.fn_corrida_por_pessoas(p_corrida, p_corredores, p_plateia)) LOOP
    PERFORM public.fn_corrida_avisar_pessoa(v_u);
  END LOOP;
  -- Mudou o papel de quem já estava (passou a correr, por exemplo): o estado
  -- pessoal de todo mundo segue pela sala.
  PERFORM public.fn_corrida_avisar_sala(p_corrida, 'pessoas');
  RETURN public.fn_corrida_painel();
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_corrida_abrir(p_corrida bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_u uuid;
BEGIN
  PERFORM public.fn_corrida_exigir_admin();
  UPDATE public.corridas SET estado = 'aberta', aberta_em = clock_timestamp(), versao = versao + 1
   WHERE id = p_corrida AND estado = 'preparando';
  IF NOT FOUND THEN
    RAISE EXCEPTION 'NAO_DA: só abre uma corrida em preparação' USING ERRCODE = 'P0001';
  END IF;
  -- O card «Assistir» chega para todo mundo que foi chamado.
  FOR v_u IN SELECT usuario FROM public.corrida_pessoas WHERE corrida_id = p_corrida LOOP
    PERFORM public.fn_corrida_avisar_pessoa(v_u);
  END LOOP;
  PERFORM public.fn_corrida_avisar_sala(p_corrida, 'estado');
  RETURN public.fn_corrida_painel();
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_corrida_escolher(p_corrida bigint, p_escolha smallint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_eu uuid := auth.uid();
  v_c  public.corridas%ROWTYPE;
BEGIN
  IF v_eu IS NULL THEN
    RAISE EXCEPTION 'NAO_AUTENTICADO' USING ERRCODE = '42501';
  END IF;
  IF p_escolha IS NULL OR p_escolha NOT BETWEEN 0 AND 2 THEN
    RAISE EXCEPTION 'ESCOLHA_INVALIDA' USING ERRCODE = '22023';
  END IF;
  SELECT * INTO v_c FROM public.corridas WHERE id = p_corrida;
  IF NOT FOUND OR v_c.estado NOT IN ('preparando', 'aberta') OR v_c.gravada_em IS NOT NULL THEN
    RAISE EXCEPTION 'ESCOLHA_FECHADA: a corrida já foi gravada; o bichinho ficou o que estava' USING ERRCODE = 'P0001';
  END IF;
  UPDATE public.corrida_pessoas SET escolha = p_escolha, escolhida_em = clock_timestamp()
   WHERE corrida_id = p_corrida AND usuario = v_eu AND corre;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'NAO_CORRE: você não está nesta corrida' USING ERRCODE = '42501';
  END IF;
  IF v_c.estado = 'aberta' THEN
    PERFORM public.fn_corrida_avisar_sala(p_corrida, 'escolha', jsonb_build_object('usuario', v_eu, 'escolha', p_escolha));
  END IF;
  RETURN public.fn_corrida_minha_de(v_eu);
END;
$function$;

-- Entrar no lobby. O aviso sai no máximo a cada 1,5 s, levando todo mundo
-- que entrou desde o anterior.
CREATE OR REPLACE FUNCTION public.fn_corrida_entrar(p_corrida bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_eu    uuid := auth.uid();
  v_c     public.corridas%ROWTYPE;
  v_novo  boolean;
BEGIN
  IF v_eu IS NULL THEN
    RAISE EXCEPTION 'NAO_AUTENTICADO' USING ERRCODE = '42501';
  END IF;
  SELECT * INTO v_c FROM public.corridas WHERE id = p_corrida;
  IF NOT FOUND OR v_c.estado NOT IN ('aberta', 'correndo') THEN
    RAISE EXCEPTION 'SEM_LOBBY: a corrida não está aberta' USING ERRCODE = 'P0001';
  END IF;
  UPDATE public.corrida_pessoas SET entrou_em = clock_timestamp()
   WHERE corrida_id = p_corrida AND usuario = v_eu AND entrou_em IS NULL;
  v_novo := FOUND;
  IF NOT v_novo AND NOT EXISTS (SELECT 1 FROM public.corrida_pessoas WHERE corrida_id = p_corrida AND usuario = v_eu)
     AND NOT public.fn_user_is_super_admin() THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: você não foi chamado para esta corrida' USING ERRCODE = '42501';
  END IF;

  IF v_novo THEN
    SELECT * INTO v_c FROM public.corridas WHERE id = p_corrida FOR UPDATE;
    IF v_c.lobby_avisado_em IS NULL OR v_c.lobby_avisado_em < clock_timestamp() - interval '1.5 seconds' THEN
      PERFORM realtime.send(
        jsonb_build_object('agora', clock_timestamp(),
          'entraram', coalesce((SELECT jsonb_agg(jsonb_build_object('usuario', p.usuario, 'entrou_em', p.entrou_em))
                                  FROM public.corrida_pessoas p
                                 WHERE p.corrida_id = p_corrida AND p.entrou_em IS NOT NULL
                                   AND p.entrou_em > coalesce(v_c.lobby_avisado_em, '-infinity'::timestamptz) - interval '2 seconds'), '[]'::jsonb)),
        'lobby', 'corrida-sala:' || p_corrida::text, true);
      UPDATE public.corridas SET lobby_avisado_em = clock_timestamp() WHERE id = p_corrida;
    END IF;
  END IF;
  RETURN public.fn_corrida_sala(p_corrida);
END;
$function$;

-- A gravação: o navegador do super_admin simulou a corrida e subiu os
-- arquivos. Daqui em diante ninguém troca o bichinho, as pessoas nem o prêmio.
-- `p_gravacao` nulo descarta a gravação (para gravar de novo).
CREATE OR REPLACE FUNCTION public.fn_corrida_gravar(p_corrida bigint, p_gravacao jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_c        public.corridas%ROWTYPE;
  v_vencedor uuid;
BEGIN
  PERFORM public.fn_corrida_exigir_admin();
  SELECT * INTO v_c FROM public.corridas WHERE id = p_corrida FOR UPDATE;
  IF NOT FOUND OR v_c.estado NOT IN ('preparando', 'aberta') THEN
    RAISE EXCEPTION 'NAO_DA: a corrida já largou ou terminou' USING ERRCODE = 'P0001';
  END IF;
  IF p_gravacao IS NOT NULL THEN
    IF NOT (p_gravacao ? 'arquivo' AND p_gravacao ? 'mapa' AND p_gravacao ? 'semente' AND p_gravacao ? 'vencedor') THEN
      RAISE EXCEPTION 'GRAVACAO_INCOMPLETA: faltou arquivo, mapa, semente ou vencedor' USING ERRCODE = '22023';
    END IF;
    BEGIN
      v_vencedor := (p_gravacao->>'vencedor')::uuid;
    EXCEPTION WHEN invalid_text_representation THEN
      RAISE EXCEPTION 'GRAVACAO_INCOMPLETA: vencedor inválido' USING ERRCODE = '22023';
    END;
    IF NOT EXISTS (SELECT 1 FROM public.corrida_pessoas WHERE corrida_id = p_corrida AND usuario = v_vencedor AND corre) THEN
      RAISE EXCEPTION 'GRAVACAO_INCOMPLETA: o vencedor não está correndo' USING ERRCODE = '22023';
    END IF;
  END IF;

  UPDATE public.corridas
     SET gravacao = p_gravacao,
         gravada_em = CASE WHEN p_gravacao IS NULL THEN NULL ELSE clock_timestamp() END,
         vencedor = v_vencedor,
         vencedor_nome = (SELECT nome FROM public.corrida_pessoas WHERE corrida_id = p_corrida AND usuario = v_vencedor),
         versao = versao + 1
   WHERE id = p_corrida;
  PERFORM public.fn_corrida_avisar_sala(p_corrida, 'estado');
  RETURN public.fn_corrida_painel();
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_corrida_iniciar(p_corrida bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  PERFORM public.fn_corrida_exigir_admin();
  -- 4 s de folga: o aviso chega a todas as telas antes da contagem começar.
  UPDATE public.corridas
     SET estado = 'correndo', inicia_em = clock_timestamp() + interval '4 seconds', versao = versao + 1
   WHERE id = p_corrida AND estado = 'aberta' AND gravada_em IS NOT NULL;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'NAO_DA: a corrida precisa estar aberta e gravada para largar' USING ERRCODE = 'P0001';
  END IF;
  PERFORM public.fn_corrida_avisar_sala(p_corrida, 'estado');
  RETURN public.fn_corrida_painel();
END;
$function$;

-- Encerrar (depois da festa) ou cancelar (a qualquer momento antes).
CREATE OR REPLACE FUNCTION public.fn_corrida_encerrar(p_corrida bigint, p_cancelar boolean DEFAULT false)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_c public.corridas%ROWTYPE;
  v_u uuid;
BEGIN
  PERFORM public.fn_corrida_exigir_admin();
  SELECT * INTO v_c FROM public.corridas WHERE id = p_corrida FOR UPDATE;
  IF NOT FOUND OR v_c.estado NOT IN ('preparando', 'aberta', 'correndo') THEN
    RAISE EXCEPTION 'NAO_DA: a corrida já terminou' USING ERRCODE = 'P0001';
  END IF;
  UPDATE public.corridas
     SET estado = CASE WHEN p_cancelar OR v_c.estado <> 'correndo' THEN 'cancelada' ELSE 'encerrada' END,
         encerrada_em = clock_timestamp(), versao = versao + 1
   WHERE id = p_corrida;
  PERFORM public.fn_corrida_avisar_sala(p_corrida, 'estado');
  -- Cancelada antes de abrir: só quem corre sabia dela (e não ouve a sala sem ter aberto o app nela).
  FOR v_u IN SELECT usuario FROM public.corrida_pessoas WHERE corrida_id = p_corrida AND (corre OR v_c.estado <> 'preparando') LOOP
    PERFORM public.fn_corrida_avisar_pessoa(v_u);
  END LOOP;
  RETURN public.fn_corrida_painel();
END;
$function$;

-- ── O card de divulgação ───────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.fn_corrida_divulgar(p_titulo text, p_mensagem text, p_premio text, p_alvos uuid[], p_dias integer DEFAULT 3)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_id bigint;
  v_u  uuid;
BEGIN
  PERFORM public.fn_corrida_exigir_admin();
  IF coalesce(array_length(p_alvos, 1), 0) = 0 THEN
    RAISE EXCEPTION 'SEM_ALVO: escolha quem vai ver o card' USING ERRCODE = 'P0001';
  END IF;
  INSERT INTO public.corrida_divulgacoes (titulo, mensagem, premio, criada_por, expira_em)
  VALUES (btrim(p_titulo), btrim(p_mensagem), nullif(btrim(p_premio), ''), auth.uid(),
          clock_timestamp() + make_interval(days => least(greatest(coalesce(p_dias, 3), 1), 30)))
  RETURNING id INTO v_id;
  INSERT INTO public.corrida_divulgacao_alvos (divulgacao_id, usuario)
  SELECT v_id, pf.id FROM public.perfis pf WHERE pf.id = ANY (p_alvos)
  ON CONFLICT DO NOTHING;
  FOR v_u IN SELECT usuario FROM public.corrida_divulgacao_alvos WHERE divulgacao_id = v_id LOOP
    PERFORM public.fn_corrida_avisar_pessoa(v_u);
  END LOOP;
  RETURN public.fn_corrida_painel();
END;
$function$;

