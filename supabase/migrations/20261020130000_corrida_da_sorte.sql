-- ── Os arquivos da gravação: bucket `corridas`, pasta = id da corrida ──────
-- Privado: só quem foi chamado para a corrida baixa (o app baixa e toca do
-- próprio navegador). Só o super_admin envia.
DO $storage$
BEGIN
  IF to_regclass('storage.buckets') IS NULL THEN
    RETURN;
  END IF;
  INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
  VALUES ('corridas', 'corridas', FALSE, 26214400, ARRAY['application/octet-stream', 'video/webm'])
  ON CONFLICT (id) DO UPDATE
    SET public = FALSE, file_size_limit = EXCLUDED.file_size_limit, allowed_mime_types = EXCLUDED.allowed_mime_types;

  EXECUTE 'DROP POLICY IF EXISTS corridas_ler ON storage.objects';
  EXECUTE $p$CREATE POLICY corridas_ler ON storage.objects FOR SELECT TO authenticated
    USING (bucket_id = 'corridas' AND (storage.foldername(name))[1] ~ '^[0-9]+$'
           AND public.fn_corrida_posso_ver(((storage.foldername(name))[1])::bigint))$p$;
  EXECUTE 'DROP POLICY IF EXISTS corridas_escrever ON storage.objects';
  EXECUTE $p$CREATE POLICY corridas_escrever ON storage.objects FOR INSERT TO authenticated
    WITH CHECK (bucket_id = 'corridas' AND public.fn_user_is_super_admin())$p$;
  EXECUTE 'DROP POLICY IF EXISTS corridas_trocar ON storage.objects';
  EXECUTE $p$CREATE POLICY corridas_trocar ON storage.objects FOR UPDATE TO authenticated
    USING (bucket_id = 'corridas' AND public.fn_user_is_super_admin())$p$;
  EXECUTE 'DROP POLICY IF EXISTS corridas_apagar ON storage.objects';
  EXECUTE $p$CREATE POLICY corridas_apagar ON storage.objects FOR DELETE TO authenticated
    USING (bucket_id = 'corridas' AND public.fn_user_is_super_admin())$p$;
END;
$storage$;

