-- ============================================================================
-- Tickets — a fila de pedidos da lideranca para quem desenvolve
-- ============================================================================
--
-- ## O problema
--
-- Trocar senha, corrigir acordo, investigar erro, liberar acesso: os pedidos
-- chegavam por WhatsApp, cada um em uma conversa, e a fila real so existia na
-- cabeca de duas pessoas. Nao havia estado ("ja estao vendo?"), nao havia
-- historico ("o que decidimos daquela vez?") e nao havia dono.
--
-- ## O desenho
--
-- Um ticket tem SETOR (o de quem abriu), CATEGORIA e ESTADO. Quem abre e a
-- lideranca; quem resolve e uma lista curta e explicita — administradores por
-- padrao, mais quem for autorizado em `tickets_atendentes`.
--
--   aberto -> em_andamento -> concluido
--                 |    \-----> pendente (esperando algo de quem abriu)
--                 \---------> recusado
--   cancelado: so quem abriu, e so enquanto nao estiver concluido/recusado.
--
-- ## Quem ve o que
--
--   * quem abriu ......... o proprio ticket, sempre;
--   * lideranca do setor . todos os tickets DO SETOR dela (o pedido de um lider
--                          do Play 5 e assunto da lideranca do Play 5 inteira);
--   * diretoria .......... todos os setores, sem poder atender;
--   * atendentes ......... tudo, e sao os unicos que mudam estado e assumem.
--
-- Nao ha travar o chat em duas pessoas, como na Ouvidoria: quem enxerga o
-- ticket fala nele. Foi pedido assim — o assunto e da lideranca do setor, nao
-- de um individuo.
--
-- ## A aba nasce fechada
--
-- `tickets_config.liberado_para_lideranca` comeca FALSE: no primeiro dia so
-- administrador ve a aba, para conferir em producao com dados de verdade antes
-- de a lideranca inteira entrar. O botao que vira a chave fica na propria aba.
--
-- ## Notificacao mora no banco
--
-- Os gatilhos abaixo escrevem em `notificacoes`. Poderiam viver no cliente,
-- como em outras telas — e ai uma aba fechada no meio da acao deixaria alguem
-- sem aviso, e um INSERT feito por outro caminho nao avisaria ninguem. Como
-- SECURITY DEFINER no gatilho, a regra vale para toda escrita, venha de onde
-- vier. As regras, uma por uma:
--
--   * ticket novo ........ avisa todos os atendentes (menos quem abriu);
--   * mensagem ........... avisa quem abriu e quem assumiu (menos o autor);
--   * mudanca de estado .. avisa quem abriu e quem assumiu (menos o autor).
--
-- E por isso que um administrador que ainda nao assumiu o ticket nao recebe
-- notificacao de cada mensagem: ele recebeu a de abertura, e o resto e ruido
-- ate ele decidir que aquele ticket e dele.
-- ============================================================================

-- ── Tabelas ─────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.tickets (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Numero curto para as pessoas conversarem ("o 42 ja saiu?"). Sequencia
  -- global de propriedade da coluna: por empresa exigiria serializar os
  -- INSERTs, e o ganho seria estetico.
  numero         BIGINT GENERATED BY DEFAULT AS IDENTITY,
  empresa_id     UUID NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
  -- Setor de quem abriu, CONGELADO no momento da abertura: o pedido continua
  -- sendo do Play 5 mesmo depois de a pessoa mudar de setor.
  setor_id       UUID REFERENCES public.setores(id) ON DELETE SET NULL,
  aberto_por     UUID NOT NULL REFERENCES public.perfis(id) ON DELETE CASCADE,
  -- Copias do nome: a lista abre sem JOIN e sobrevive a exclusao do perfil.
  aberto_por_nome TEXT,
  categoria      TEXT NOT NULL,
  assunto        TEXT NOT NULL,
  descricao      TEXT,
  prioridade     TEXT NOT NULL DEFAULT 'normal'
                 CHECK (prioridade IN ('baixa','normal','alta','urgente')),
  status         TEXT NOT NULL DEFAULT 'aberto'
                 CHECK (status IN ('aberto','em_andamento','pendente','concluido','recusado','cancelado')),
  responsavel_id   UUID REFERENCES public.perfis(id) ON DELETE SET NULL,
  responsavel_nome TEXT,
  -- Campos extras da categoria (usuario citado, aba com erro, NR...). JSONB
  -- porque o conjunto muda com a categoria e todos sao opcionais — uma coluna
  -- por campo viraria uma tabela larga e quase toda nula.
  campos         JSONB NOT NULL DEFAULT '{}'::JSONB,
  criado_em      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  atualizado_em  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  fechado_em     TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_tickets_empresa_status ON public.tickets(empresa_id, status);
CREATE INDEX IF NOT EXISTS idx_tickets_setor          ON public.tickets(setor_id);
CREATE INDEX IF NOT EXISTS idx_tickets_aberto_por     ON public.tickets(aberto_por);
CREATE INDEX IF NOT EXISTS idx_tickets_criado_em      ON public.tickets(criado_em DESC);

CREATE TABLE IF NOT EXISTS public.tickets_mensagens (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id  UUID NOT NULL REFERENCES public.tickets(id) ON DELETE CASCADE,
  autor_id   UUID REFERENCES public.perfis(id) ON DELETE SET NULL,
  autor_nome TEXT,
  autor_foto TEXT,
  texto      TEXT,
  -- [{ url, nome, tipo, tamanho }]. O arquivo vive no bucket `tickets`; aqui
  -- fica so o endereco, para a mensagem carregar sem uma segunda consulta.
  anexos     JSONB NOT NULL DEFAULT '[]'::JSONB,
  criado_em  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (COALESCE(TRIM(texto), '') <> '' OR jsonb_array_length(anexos) > 0)
);

CREATE INDEX IF NOT EXISTS idx_tickets_msg_ticket ON public.tickets_mensagens(ticket_id, criado_em);

-- Trilha do ticket. Escrita SO por gatilho: um historico que depende de o
-- cliente lembrar de gravar e um historico com buracos.
CREATE TABLE IF NOT EXISTS public.tickets_eventos (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id  UUID NOT NULL REFERENCES public.tickets(id) ON DELETE CASCADE,
  autor_id   UUID,
  autor_nome TEXT,
  tipo       TEXT NOT NULL,
  de         TEXT,
  para       TEXT,
  criado_em  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tickets_ev_ticket ON public.tickets_eventos(ticket_id, criado_em);

-- Quem, alem dos administradores, pode atender.
CREATE TABLE IF NOT EXISTS public.tickets_atendentes (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  empresa_id UUID NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
  perfil_id  UUID NOT NULL REFERENCES public.perfis(id) ON DELETE CASCADE,
  criado_por UUID,
  criado_em  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (empresa_id, perfil_id)
);

CREATE TABLE IF NOT EXISTS public.tickets_config (
  empresa_id UUID PRIMARY KEY REFERENCES public.empresas(id) ON DELETE CASCADE,
  liberado_para_lideranca BOOLEAN NOT NULL DEFAULT FALSE,
  atualizado_por UUID,
  atualizado_em  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ── Quem pode atender ───────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.fn_ticket_pode_atender()
RETURNS BOOLEAN
LANGUAGE SQL STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  SELECT public.fn_user_is_super_admin()
      OR public.fn_user_has_any_role(ARRAY['administrador'])
      OR EXISTS (
           SELECT 1 FROM public.tickets_atendentes a
            WHERE a.perfil_id = (SELECT auth.uid())
         );
$$;

COMMENT ON FUNCTION public.fn_ticket_pode_atender() IS
  'Administrador e super_admin sempre; os demais, so se estiverem em tickets_atendentes.';

CREATE OR REPLACE FUNCTION public.fn_ticket_visivel(
  p_empresa_id UUID, p_setor_id UUID, p_aberto_por UUID
)
RETURNS BOOLEAN
LANGUAGE SQL STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  SELECT public.fn_can_access_empresa(p_empresa_id)
     AND (
          p_aberto_por = (SELECT auth.uid())
       OR public.fn_ticket_pode_atender()
       -- Diretoria enxerga todos os setores, sem atender.
       OR public.fn_user_has_any_role(ARRAY['diretoria'])
       -- Lideranca: o proprio setor, e so ele.
       OR (public.fn_user_has_any_role(ARRAY['lider','elite','gerencia','ouvidoria'])
           AND p_setor_id IS NOT DISTINCT FROM public.fn_user_setor_id())
     );
$$;

-- Quem abre: lideranca para cima. Operador nao abre ticket — o pedido dele
-- passa pelo lider, que e quem tem o contexto.
CREATE OR REPLACE FUNCTION public.fn_ticket_pode_abrir()
RETURNS BOOLEAN
LANGUAGE SQL STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  SELECT public.fn_user_is_super_admin()
      OR public.fn_user_has_any_role(
           ARRAY['lider','elite','gerencia','diretoria','administrador','ouvidoria']
         );
$$;

