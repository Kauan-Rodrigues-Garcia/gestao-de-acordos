-- ── Guarda de edicao ────────────────────────────────────────────────────────

/*
 * Quem abriu pode CANCELAR e mais nada.
 *
 * A politica de UPDATE deixa o autor escrever na linha; sem este gatilho ele
 * poderia se marcar como concluido, trocar a categoria depois de resolvido ou
 * se colocar como responsavel. O recorte e por coluna, e RLS nao faz isso.
 */
CREATE OR REPLACE FUNCTION public.fn_ticket_guarda_edicao()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
BEGIN
  IF public.fn_ticket_pode_atender() THEN
    RETURN NEW;
  END IF;

  IF OLD.aberto_por <> auth.uid() THEN
    RAISE EXCEPTION 'TICKET_SEM_PERMISSAO: apenas quem atende pode alterar este ticket'
      USING ERRCODE = '42501';
  END IF;

  IF NEW.status <> 'cancelado' OR OLD.status IN ('concluido','recusado','cancelado') THEN
    RAISE EXCEPTION 'TICKET_SEM_PERMISSAO: quem abriu so pode cancelar um ticket ainda em aberto'
      USING ERRCODE = '42501';
  END IF;

  -- Cancelar e mudar UMA coisa. Tudo o mais volta ao que era.
  NEW.numero          := OLD.numero;
  NEW.empresa_id      := OLD.empresa_id;
  NEW.setor_id        := OLD.setor_id;
  NEW.aberto_por      := OLD.aberto_por;
  NEW.aberto_por_nome := OLD.aberto_por_nome;
  NEW.categoria       := OLD.categoria;
  NEW.assunto         := OLD.assunto;
  NEW.descricao       := OLD.descricao;
  NEW.prioridade      := OLD.prioridade;
  NEW.responsavel_id  := OLD.responsavel_id;
  NEW.responsavel_nome:= OLD.responsavel_nome;
  NEW.campos          := OLD.campos;
  NEW.criado_em       := OLD.criado_em;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_ticket_guarda_edicao ON public.tickets;
CREATE TRIGGER trg_ticket_guarda_edicao
BEFORE UPDATE ON public.tickets
FOR EACH ROW EXECUTE FUNCTION public.fn_ticket_guarda_edicao();

CREATE OR REPLACE FUNCTION public.fn_ticket_carimbar()
RETURNS TRIGGER
LANGUAGE plpgsql SET search_path TO 'public'
AS $$
BEGIN
  NEW.atualizado_em := NOW();
  IF NEW.status IN ('concluido','recusado','cancelado')
     AND OLD.status NOT IN ('concluido','recusado','cancelado') THEN
    NEW.fechado_em := NOW();
  ELSIF NEW.status NOT IN ('concluido','recusado','cancelado') THEN
    NEW.fechado_em := NULL;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_ticket_carimbar ON public.tickets;
CREATE TRIGGER trg_ticket_carimbar
BEFORE UPDATE ON public.tickets
FOR EACH ROW EXECUTE FUNCTION public.fn_ticket_carimbar();

-- ── Trilha + notificacao ────────────────────────────────────────────────────

/** Nome de quem esta agindo, para a trilha e para a notificacao. */
CREATE OR REPLACE FUNCTION public.fn_ticket_nome_do_autor()
RETURNS TEXT
LANGUAGE SQL STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  SELECT COALESCE(nome, usuario, 'Sistema') FROM public.perfis WHERE id = (SELECT auth.uid());
$$;

/**
 * Uma notificacao por destinatario, pulando quem esta agindo.
 *
 * `p_destinos` chega com nulos e repetidos de proposito — quem chama nao
 * precisa saber se o ticket tem responsavel nem se o autor e o proprio dono.
 */
CREATE OR REPLACE FUNCTION public.fn_ticket_notificar(
  p_empresa_id UUID, p_ticket_id UUID, p_destinos UUID[],
  p_titulo TEXT, p_mensagem TEXT
)
RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE
  v_autor UUID := auth.uid();
  v_nome  TEXT := public.fn_ticket_nome_do_autor();
  v_foto  TEXT;
BEGIN
  SELECT foto_url INTO v_foto FROM public.perfis WHERE id = v_autor;

  INSERT INTO public.notificacoes
    (usuario_id, empresa_id, titulo, mensagem, rota, autor_id, autor_nome, autor_foto)
  SELECT DISTINCT d, p_empresa_id, p_titulo, p_mensagem,
         '/tickets?ticket=' || p_ticket_id::TEXT, v_autor, v_nome, v_foto
    FROM unnest(p_destinos) AS d
   WHERE d IS NOT NULL AND d IS DISTINCT FROM v_autor;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_ticket_apos_insert()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE
  v_destinos UUID[];
BEGIN
  INSERT INTO public.tickets_eventos (ticket_id, autor_id, autor_nome, tipo, para)
  VALUES (NEW.id, auth.uid(), public.fn_ticket_nome_do_autor(), 'aberto', NEW.status);

  -- Administradores da empresa + quem foi autorizado a mao. Um ticket sem
  -- ninguem avisado e um ticket que so aparece quando alguem abre a aba.
  SELECT array_agg(id) INTO v_destinos FROM (
    SELECT p.id FROM public.perfis p
     WHERE p.empresa_id = NEW.empresa_id
       AND p.perfil IN ('administrador','super_admin')
       AND COALESCE(p.ativo, TRUE)
    UNION
    SELECT a.perfil_id FROM public.tickets_atendentes a
     WHERE a.empresa_id = NEW.empresa_id
  ) AS alvos;

  PERFORM public.fn_ticket_notificar(
    NEW.empresa_id, NEW.id, v_destinos,
    'Novo ticket #' || NEW.numero,
    COALESCE(NEW.aberto_por_nome, 'Alguem') || ' abriu: ' || NEW.assunto
  );
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_ticket_apos_insert ON public.tickets;
CREATE TRIGGER trg_ticket_apos_insert
AFTER INSERT ON public.tickets
FOR EACH ROW EXECUTE FUNCTION public.fn_ticket_apos_insert();

CREATE OR REPLACE FUNCTION public.fn_ticket_apos_update()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE
  v_nome TEXT := public.fn_ticket_nome_do_autor();
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO public.tickets_eventos (ticket_id, autor_id, autor_nome, tipo, de, para)
    VALUES (NEW.id, auth.uid(), v_nome, 'status', OLD.status, NEW.status);

    PERFORM public.fn_ticket_notificar(
      NEW.empresa_id, NEW.id, ARRAY[NEW.aberto_por, NEW.responsavel_id],
      'Ticket #' || NEW.numero || ': ' || NEW.status,
      v_nome || ' mudou o ticket "' || NEW.assunto || '" para ' || NEW.status || '.'
    );
  END IF;

  IF NEW.responsavel_id IS DISTINCT FROM OLD.responsavel_id THEN
    INSERT INTO public.tickets_eventos (ticket_id, autor_id, autor_nome, tipo, de, para)
    VALUES (NEW.id, auth.uid(), v_nome, 'responsavel',
            OLD.responsavel_nome, NEW.responsavel_nome);

    PERFORM public.fn_ticket_notificar(
      NEW.empresa_id, NEW.id, ARRAY[NEW.aberto_por, NEW.responsavel_id],
      'Ticket #' || NEW.numero || ' tem responsavel',
      COALESCE(NEW.responsavel_nome, 'Ninguem') || ' esta cuidando de "' || NEW.assunto || '".'
    );
  END IF;

  IF NEW.prioridade IS DISTINCT FROM OLD.prioridade THEN
    INSERT INTO public.tickets_eventos (ticket_id, autor_id, autor_nome, tipo, de, para)
    VALUES (NEW.id, auth.uid(), v_nome, 'prioridade', OLD.prioridade, NEW.prioridade);
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_ticket_apos_update ON public.tickets;
CREATE TRIGGER trg_ticket_apos_update
AFTER UPDATE ON public.tickets
FOR EACH ROW EXECUTE FUNCTION public.fn_ticket_apos_update();

CREATE OR REPLACE FUNCTION public.fn_ticket_apos_mensagem()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE
  t public.tickets%ROWTYPE;
BEGIN
  SELECT * INTO t FROM public.tickets WHERE id = NEW.ticket_id;
  IF NOT FOUND THEN RETURN NEW; END IF;

  -- So quem abriu e quem assumiu. O restante da lideranca do setor ve o ticket
  -- na aba; notificar todos eles transformaria a campainha em ruido de fundo,
  -- e ai ninguem olha nenhuma.
  PERFORM public.fn_ticket_notificar(
    t.empresa_id, t.id, ARRAY[t.aberto_por, t.responsavel_id],
    'Ticket #' || t.numero || ': nova mensagem',
    COALESCE(NEW.autor_nome, 'Alguem') || ': '
      || LEFT(COALESCE(NULLIF(TRIM(NEW.texto), ''), '[anexo]'), 120)
  );

  UPDATE public.tickets SET atualizado_em = NOW() WHERE id = NEW.ticket_id;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_ticket_apos_mensagem ON public.tickets_mensagens;
CREATE TRIGGER trg_ticket_apos_mensagem
AFTER INSERT ON public.tickets_mensagens
FOR EACH ROW EXECUTE FUNCTION public.fn_ticket_apos_mensagem();

