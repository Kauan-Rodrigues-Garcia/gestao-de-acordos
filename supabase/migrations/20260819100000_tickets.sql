USING (
  public.fn_ticket_visivel(empresa_id, setor_id, aberto_por)
  AND (public.fn_ticket_pode_atender() OR aberto_por = (SELECT auth.uid()))
)
WITH CHECK (
  public.fn_ticket_visivel(empresa_id, setor_id, aberto_por)
  AND (public.fn_ticket_pode_atender() OR aberto_por = (SELECT auth.uid()))
);

