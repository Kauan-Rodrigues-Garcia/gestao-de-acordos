-- Votação da categoria da corrida (22/10/2026).
--
-- O pedido: ao criar uma corrida, quem foi chamado (quem corre e quem assiste)
-- vota em 30 segundos qual corrida prefere, bichinhos ou cavalos. Acabou a
-- contagem, vale a que tiver mais votos; empate, sorteio. A corrida nasce com
-- a vencedora e abre na hora: quem votou entra direto no lobby, quem não votou
-- recebe o convite «Assistir» de sempre.
--
--   corrida_enquetes        uma por votação: quem vota, até quando, o resultado
--   corrida_enquete_votos   um voto por pessoa (dá para trocar até o fim)
--
-- O caminho:
--   fn_corrida_enquete_abrir(votantes)   super_admin; o card chega no tópico
--                                        pessoal de cada votante (`corrida-eu:<u>`,
--                                        evento «enquete»), que o app já ouve.
--   fn_corrida_enquete_votar(id, cat)    só quem foi chamado, só até `encerra_em`.
--   fn_corrida_enquete_fechar(id)        super_admin, depois da contagem: conta,
--                                        desempata no sorteio, avisa cada votante.
--
-- A corrida em si continua nas funções de sempre (fn_corrida_criar e
-- fn_corrida_abrir), chamadas pelo painel com a categoria vencedora.
--
-- Reexecutável. Desfazer: ver o fim do arquivo.

BEGIN;

SET LOCAL lock_timeout = '15s';

CREATE TABLE IF NOT EXISTS public.corrida_enquetes (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  votantes        UUID[]      NOT NULL,
  criada_por      UUID,
  criada_em       TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  encerra_em      TIMESTAMPTZ NOT NULL,
  fechada_em      TIMESTAMPTZ,
  vencedora       TEXT        CHECK (vencedora IN ('bichinhos', 'cavalos')),
  votos_bichinhos INTEGER,
  votos_cavalos   INTEGER,
  empate          BOOLEAN
);

COMMENT ON TABLE public.corrida_enquetes IS
  'Corrida da Sorte: a votação de 30 s entre bichinhos e cavalos, antes de a corrida nascer. Escrita só pelas funções fn_corrida_enquete_*. Ver 20261022130000.';

CREATE TABLE IF NOT EXISTS public.corrida_enquete_votos (
  enquete_id BIGINT      NOT NULL REFERENCES public.corrida_enquetes (id) ON DELETE CASCADE,
  usuario    UUID        NOT NULL,
  categoria  TEXT        NOT NULL CHECK (categoria IN ('bichinhos', 'cavalos')),
  votou_em   TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (enquete_id, usuario)
);

-- Sem policy: ninguém lê nem escreve direto (só pelas funções).
ALTER TABLE public.corrida_enquetes      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.corrida_enquete_votos ENABLE ROW LEVEL SECURITY;
GRANT ALL ON public.corrida_enquetes, public.corrida_enquete_votos TO service_role;

-- ── O que a pessoa recebe ──────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.fn_corrida_enquete_json(p_enquete bigint, p_usuario uuid)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT jsonb_build_object(
    'id', e.id,
    'criada_em', e.criada_em,
    'encerra_em', e.encerra_em,
    'fechada_em', e.fechada_em,
    'vencedora', e.vencedora,
    'votos', CASE WHEN e.fechada_em IS NULL THEN NULL
                  ELSE jsonb_build_object('bichinhos', e.votos_bichinhos, 'cavalos', e.votos_cavalos) END,
    'empate', e.empate,
    'votantes', cardinality(e.votantes),
    'meu_voto', (SELECT v.categoria FROM public.corrida_enquete_votos v WHERE v.enquete_id = e.id AND v.usuario = p_usuario)
  )
  FROM public.corrida_enquetes e
  WHERE e.id = p_enquete;
$function$;

CREATE OR REPLACE FUNCTION public.fn_corrida_enquete_avisar(p_enquete bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_u uuid;
BEGIN
  FOR v_u IN SELECT DISTINCT unnest(votantes) FROM public.corrida_enquetes WHERE id = p_enquete LOOP
    PERFORM realtime.send(
      jsonb_build_object('agora', clock_timestamp(), 'enquete', public.fn_corrida_enquete_json(p_enquete, v_u)),
      'enquete', 'corrida-eu:' || v_u::text, true);
  END LOOP;
END;
$function$;

-- ── Abrir (super_admin) ────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.fn_corrida_enquete_abrir(p_votantes uuid[])
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_votantes uuid[];
  v_id bigint;
BEGIN
  PERFORM public.fn_corrida_exigir_admin();
  SELECT coalesce(array_agg(DISTINCT u), '{}') INTO v_votantes FROM unnest(p_votantes) u WHERE u IS NOT NULL;
  IF cardinality(v_votantes) = 0 THEN
    RAISE EXCEPTION 'SEM_VOTANTES: chame pelo menos uma pessoa com perfil para votar' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (SELECT 1 FROM public.corridas WHERE estado IN ('preparando', 'aberta', 'correndo')) THEN
    RAISE EXCEPTION 'CORRIDA_EM_ANDAMENTO: já tem uma corrida em andamento' USING ERRCODE = '22023';
  END IF;
  -- Uma votação no ar por vez: a que ficou sem fechar (o painel fechou no meio) sai.
  UPDATE public.corrida_enquetes SET fechada_em = clock_timestamp() WHERE fechada_em IS NULL;

  INSERT INTO public.corrida_enquetes (votantes, criada_por, encerra_em)
  VALUES (v_votantes, auth.uid(), clock_timestamp() + interval '30 seconds')
  RETURNING id INTO v_id;

  PERFORM public.fn_corrida_enquete_avisar(v_id);
  RETURN jsonb_build_object('agora', clock_timestamp(), 'enquete', public.fn_corrida_enquete_json(v_id, auth.uid()));
END;
$function$;

-- ── Votar (quem foi chamado) ───────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.fn_corrida_enquete_votar(p_enquete bigint, p_categoria text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_eu uuid := auth.uid();
  e public.corrida_enquetes;
BEGIN
  IF p_categoria IS NULL OR p_categoria NOT IN ('bichinhos', 'cavalos') THEN
    RAISE EXCEPTION 'CATEGORIA_INVALIDA: escolha bichinhos ou cavalos' USING ERRCODE = '22023';
  END IF;
  SELECT * INTO e FROM public.corrida_enquetes WHERE id = p_enquete;
  IF NOT FOUND OR v_eu IS NULL OR NOT (v_eu = ANY (e.votantes)) THEN
    RAISE EXCEPTION 'NAO_AUTORIZADO: você não foi chamado para esta votação' USING ERRCODE = '42501';
  END IF;
  IF e.fechada_em IS NOT NULL OR clock_timestamp() >= e.encerra_em THEN
    RAISE EXCEPTION 'VOTACAO_ENCERRADA: o tempo da votação acabou' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.corrida_enquete_votos (enquete_id, usuario, categoria)
  VALUES (p_enquete, v_eu, p_categoria)
  ON CONFLICT (enquete_id, usuario) DO UPDATE SET categoria = EXCLUDED.categoria, votou_em = clock_timestamp();

  RETURN jsonb_build_object('agora', clock_timestamp(), 'enquete', public.fn_corrida_enquete_json(p_enquete, v_eu));
END;
$function$;

-- ── Fechar (super_admin, depois da contagem) ───────────────────────────────
CREATE OR REPLACE FUNCTION public.fn_corrida_enquete_fechar(p_enquete bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  e public.corrida_enquetes;
  v_b integer;
  v_c integer;
  v_vencedora text;
BEGIN
  PERFORM public.fn_corrida_exigir_admin();
  SELECT * INTO e FROM public.corrida_enquetes WHERE id = p_enquete FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'NAO_ACHOU: votação não encontrada' USING ERRCODE = 'P0002';
  END IF;
  -- Já fechada (clique repetido): devolve o mesmo resultado.
  IF e.vencedora IS NOT NULL THEN
    RETURN jsonb_build_object('agora', clock_timestamp(), 'enquete', public.fn_corrida_enquete_json(p_enquete, auth.uid()));
  END IF;
  IF e.fechada_em IS NOT NULL THEN
    RAISE EXCEPTION 'VOTACAO_DESCARTADA: esta votação foi substituída por outra' USING ERRCODE = '22023';
  END IF;
  -- Folga de 2 s para o relógio do painel adiantado.
  IF clock_timestamp() < e.encerra_em - interval '2 seconds' THEN
    RAISE EXCEPTION 'AINDA_VOTANDO: a votação ainda está no ar' USING ERRCODE = '22023';
  END IF;

  SELECT count(*) FILTER (WHERE categoria = 'bichinhos'), count(*) FILTER (WHERE categoria = 'cavalos')
    INTO v_b, v_c
    FROM public.corrida_enquete_votos WHERE enquete_id = p_enquete;
  v_vencedora := CASE WHEN v_b > v_c THEN 'bichinhos'
                      WHEN v_c > v_b THEN 'cavalos'
                      WHEN random() < 0.5 THEN 'bichinhos' ELSE 'cavalos' END;

  UPDATE public.corrida_enquetes
     SET fechada_em = clock_timestamp(), vencedora = v_vencedora,
         votos_bichinhos = v_b, votos_cavalos = v_c, empate = (v_b = v_c)
   WHERE id = p_enquete;

  PERFORM public.fn_corrida_enquete_avisar(p_enquete);
  RETURN jsonb_build_object('agora', clock_timestamp(), 'enquete', public.fn_corrida_enquete_json(p_enquete, auth.uid()));
END;
$function$;

-- ── Permissões ─────────────────────────────────────────────────────────────
REVOKE ALL ON FUNCTION public.fn_corrida_enquete_json(bigint, uuid)  FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.fn_corrida_enquete_avisar(bigint)      FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.fn_corrida_enquete_abrir(uuid[])       FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.fn_corrida_enquete_votar(bigint, text) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.fn_corrida_enquete_fechar(bigint)      FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_corrida_enquete_abrir(uuid[])       TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_corrida_enquete_votar(bigint, text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_corrida_enquete_fechar(bigint)      TO authenticated;

-- ── Prova ──────────────────────────────────────────────────────────────────
DO $prova$
BEGIN
  IF to_regclass('public.corrida_enquetes') IS NULL OR to_regclass('public.corrida_enquete_votos') IS NULL THEN
    RAISE EXCEPTION 'corrida enquete: faltou tabela';
  END IF;
  IF has_function_privilege('authenticated', 'public.fn_corrida_enquete_avisar(bigint)', 'EXECUTE')
     OR has_function_privilege('anon', 'public.fn_corrida_enquete_votar(bigint, text)', 'EXECUTE') THEN
    RAISE EXCEPTION 'corrida enquete: função aberta demais';
  END IF;
END;
$prova$;

COMMIT;

NOTIFY pgrst, 'reload schema';

