/** Os acentos, nas duas linhas de cima (cada um com 5 de largura). */
const ACENTOS: Readonly<Record<string, readonly [string, string]>> = {
  '́': ['...#.', '..#..'], // agudo
  '̀': ['.#...', '..#..'], // grave
  '̂': ['..#..', '.#.#.'], // circunflexo
  '̃': ['.##.#', '#.##.'], // til
};

/** O `í` do jogo: o i sem pingo, com o acento por cima. */
const I_AGUDO = '.#/../#./#./#./#./#./..';

type Glifo = readonly string[];

const cache = new Map<string, Glifo>();

/** A grade de 8 linhas de uma letra (com o acento composto, quando há). */
export function glifoMC(ch: string): Glifo {
  const pronto = cache.get(ch);
  if (pronto) return pronto;
  let g: Glifo;
  if (ch === 'í') g = I_AGUDO.split('/');
  else if (G[ch]) g = G[ch].split('/');
  else {
    const [base, ...marcas] = ch.normalize('NFD');
    const corpo = (G[base] ?? G['?']).split('/');
    const acento = marcas.map(m => ACENTOS[m]).find(Boolean);
    if (ch === 'ç' || ch === 'Ç') {
      // A cedilha na perna, embaixo do c.
      g = [...corpo.slice(0, 7), '..#..'];
    } else if (acento && base === base.toLowerCase()) {
      const w = corpo[0].length;
      const corta = (l: string) => (w >= 5 ? l : l.slice(1, 1 + w)).padEnd(w, '.').slice(0, w);
      g = [corta(acento[0]), corta(acento[1]), ...corpo.slice(2)];
    } else g = corpo;
  }
  cache.set(ch, g);
  return g;
}

/** A largura do texto em pixels (1 pixel entre letras, sem o último). */
export function larguraTextoMC(texto: string): number {
  let w = 0;
  for (const ch of texto) w += glifoMC(ch)[0].length + 1;
  return Math.max(0, w - 1);
}

/** Escreve o texto com a sombra do jogo (1 pixel para baixo e para a direita). */
export function escreverMC(c: CanvasRenderingContext2D, texto: string, x: number, y: number, cor: string, sombra: string): void {
  for (const [tinta, d] of [[sombra, 1], [cor, 0]] as const) {
    c.fillStyle = tinta;
    let px = x;
    for (const ch of texto) {
      const g = glifoMC(ch);
      for (let j = 0; j < g.length; j++) for (let i = 0; i < g[j].length; i++) if (g[j][i] === '#') c.fillRect(px + i + d, y + j + d, 1, 1);
      px += g[0].length + 1;
    }
  }
}
